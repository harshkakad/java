
import java.util.Scanner;

public class Sum {
    public static void main(String[] args) {
        Scanner sc=new Scanner(System.in);
        int a=sc.nextInt();
        int b=sc.nextInt();
        int c=a+b;
        System.out.print(c);

        float rad=sc.nextFloat();
        float area=3.14f*rad*rad;
        System.out.print(area);
    }
}
